"""Writing networks as the text files Infomap and other tools read.

Every network type in the package -- a downloaded :class:`~networks.Network`, a
generated :class:`~networks.InMemoryNetwork`, a :class:`~networks.StateNetwork`
and a :class:`~networks.MultilayerNetwork` -- writes through these functions, so
the formats are defined once:

* **link list** -- ``source target [weight]`` per line, first-order only;
* **Pajek** -- ``*Vertices`` with names, then ``*Edges`` or ``*Arcs``;
* **multilayer** -- ``*Vertices``, then ``*Intra`` (``layer node node weight``)
  and ``*Inter`` (``layer node layer weight``);
* **states** -- written by :meth:`StateNetwork.write`.

Node ids are kept verbatim when every label is a non-negative integer, so a
file written from a generator lines up with its planted partition: Infomap
reports the same ids back. Any other labels are numbered ``1..N`` in first-seen
order and survive as ``*Vertices`` names. Infomap accepts zero-based ids, which
is what the generators produce.

Files are written to a scratch name and renamed into place, so a failure half
way through a large network never leaves a truncated file behind.
"""

from __future__ import annotations

import numbers
import os
import re
from collections.abc import Callable, Hashable, Iterable, Iterator, Mapping
from contextlib import contextmanager
from pathlib import Path
from typing import IO, Any

__all__ = [
    "Link",
    "atomic",
    "describe",
    "node_ids",
    "ordered",
    "output_path",
    "printable",
    "write_link_list",
    "write_multilayer",
    "write_pajek",
]

#: One first-order link: ``(source, target, weight)``, weight ``None`` if unweighted.
Link = tuple[Hashable, Hashable, float | None]

_UNSAFE = re.compile(r"[\s/\\:]+")


def output_path(directory: str | Path, name: str, suffix: str) -> Path:
    """``directory / (name + suffix)``, creating *directory* if needed.

    *name* is the network's own name unless the caller overrides it; path
    separators and whitespace in it become underscores, so a dataset name can
    never escape *directory*.

    Raises:
        ValueError: *name* is empty after cleaning.
        NotADirectoryError: *directory* exists and is a file.
    """
    # Capped well below the usual 255-byte limit, leaving room for the scratch
    # file's prefix and suffix during the write.
    stem = _UNSAFE.sub("_", name).strip("._")[:200]
    if not stem:
        raise ValueError(f"{name!r} is not usable as a file name; pass name=...")
    folder = Path(directory).expanduser()
    if folder.exists() and not folder.is_dir():
        raise NotADirectoryError(f"{folder} is a file; to_pajek() takes a directory.")
    folder.mkdir(parents=True, exist_ok=True)
    return folder / f"{stem}{suffix}"


def printable(name: str) -> str:
    """Make a label safe inside a quoted name field.

    Whitespace is collapsed so a label cannot inject newlines into the file,
    and double quotes -- the field delimiters -- become single.
    """
    return " ".join(name.split()).replace('"', "'")


def _is_id(label: Any) -> bool:
    # numbers.Integral covers numpy integers, which samplers often hand back.
    return isinstance(label, numbers.Integral) and not isinstance(label, bool) and int(label) >= 0


def node_ids(labels: Iterable[Hashable]) -> dict[Hashable, int]:
    """Map node labels to the integer ids written to file.

    Verbatim, in ascending order, when every label is a non-negative integer;
    otherwise ``1..N`` in first-seen order.
    """
    seen = list(dict.fromkeys(labels))
    if all(_is_id(label) for label in seen):
        return {label: int(label) for label in sorted(seen)}  # type: ignore[type-var,call-overload]
    return {label: index for index, label in enumerate(seen, start=1)}


def ordered(labels: Iterable[Hashable]) -> list[Hashable]:
    """Sort labels of any kind: integers numerically, anything else by ``repr``."""
    return sorted(set(labels), key=lambda x: (0, x, "") if _is_id(x) else (1, 0, repr(x)))


def describe(name: str, info: Mapping[str, Any] | None) -> list[str]:
    """Header comment lines: the name, and how a synthetic network was made."""
    lines = [name] if name else []
    if info:
        generator = info.get("generator")
        parameters = info.get("parameters") or {}
        if generator:
            settings = " ".join(f"{key}={value}" for key, value in parameters.items())
            lines.append(f"generated by {generator}" + (f": {settings}" if settings else ""))
    return lines


def _weight(value: float) -> str:
    # repr is the shortest round-trip form, so the file carries exactly the
    # weights to_infomap() would feed the API.
    return repr(float(value))


@contextmanager
def atomic(target: Path) -> Iterator[IO[str]]:
    """Open a scratch file next to *target* and rename it into place on success."""
    scratch = target.with_name(f".{target.name}.{os.getpid()}.part")
    try:
        with scratch.open("w", encoding="utf-8") as out:
            yield out
        os.replace(scratch, target)
    finally:
        scratch.unlink(missing_ok=True)


def _comments(out: IO[str], comments: Iterable[str]) -> None:
    for line in comments:
        out.write(f"# {printable(line)}\n")


def write_pajek(
    target: Path,
    *,
    nodes: Iterable[Hashable],
    links: Callable[[], Iterable[Link]],
    directed: bool,
    names: Mapping[Any, str] | None = None,
    comments: Iterable[str] = (),
) -> Path:
    """Write a first-order Pajek file: ``*Vertices``, then ``*Edges`` or ``*Arcs``.

    *links* is a callable rather than an iterable so a file-backed network can
    stream its links once the vertices are written, without holding them all.
    Every node in *nodes* gets a ``*Vertices`` line, isolated ones included;
    *names* overrides the label shown for a node.
    """
    ids = node_ids(nodes)
    names = names or {}
    with atomic(target) as out:
        _comments(out, comments)
        out.write(f"*Vertices {len(ids)}\n")
        for label, index in ids.items():
            out.write(f'{index} "{printable(str(names.get(label, label)))}"\n')
        out.write("*Arcs\n" if directed else "*Edges\n")
        for source, dest, weight in links():
            line = f"{ids[source]} {ids[dest]}"
            out.write(line + (f" {_weight(weight)}\n" if weight is not None else "\n"))
    return target


def write_link_list(
    target: Path,
    *,
    links: Iterable[Link],
    directed: bool,
    comments: Iterable[str] = (),
) -> Path:
    """Write ``source target [weight]`` lines.

    A link list has no place for names, so it takes non-negative integer node
    labels only -- renumbering silently would cut the file loose from every
    partition and attribute keyed by the original labels. Nor has it a place
    for isolated nodes: a node without links is not in the file.

    Raises:
        ValueError: A node label is not a non-negative integer.
    """
    with atomic(target) as out:
        _comments(out, comments)
        out.write(f"# {'directed' if directed else 'undirected'}\n")
        for source, dest, weight in links:
            if not (_is_id(source) and _is_id(dest)):
                raise ValueError(
                    f"node {source if not _is_id(source) else dest!r} is not a non-negative "
                    "integer, and a link list cannot carry names. Use to_pajek() instead."
                )
            line = f"{int(source)} {int(dest)}"  # type: ignore[call-overload]
            out.write(line + (f" {_weight(weight)}\n" if weight is not None else "\n"))
    return target


def write_multilayer(
    target: Path,
    *,
    intra: Mapping[Hashable, Mapping[tuple[Hashable, Hashable], float]],
    inter: Mapping[tuple[tuple[Hashable, Hashable], tuple[Hashable, Hashable]], float],
    nodes: Iterable[Hashable],
    layers: Iterable[Hashable] | None = None,
    names: Mapping[Any, str] | None = None,
    comments: Iterable[str] = (),
) -> Path:
    """Write Infomap's multilayer format: ``*Vertices``, ``*Intra``, ``*Inter``.

    *intra* is ``{layer: {(u, v): weight}}``; *inter* is
    ``{((node, layer), (node, layer)): weight}``, each link staying on one
    physical node, as ``*Inter`` requires -- Infomap spreads such a link to
    the node's neighbours in the target layer. A network with no inter-layer
    links gets ``*Intra`` alone, and Infomap couples its layers with the relax
    rate at analysis time.

    *layers* fixes the layer order, and so the ids of non-integer layers; by
    default it is every layer a link mentions.
    """
    node_id = node_ids(nodes)
    if layers is None:
        layers = ordered([*intra, *(layer for pair in inter for _, layer in pair)])
    layer_id = node_ids(layers)
    names = names or {}
    with atomic(target) as out:
        _comments(out, comments)
        if any(not _is_id(layer) for layer in layer_id):
            for layer, index in layer_id.items():
                out.write(f"# layer {index} = {printable(str(layer))}\n")
        out.write(f"*Vertices {len(node_id)}\n")
        for label, index in node_id.items():
            out.write(f'{index} "{printable(str(names.get(label, label)))}"\n')
        out.write("*Intra\n# layer node node weight\n")
        for layer in layer_id:
            for (u, v), w in intra.get(layer, {}).items():
                out.write(f"{layer_id[layer]} {node_id[u]} {node_id[v]} {_weight(w)}\n")
        if inter:
            out.write("*Inter\n# layer node layer weight\n")
            for ((u, a), (_, b)), w in inter.items():
                out.write(f"{layer_id[a]} {node_id[u]} {layer_id[b]} {_weight(w)}\n")
    return target
